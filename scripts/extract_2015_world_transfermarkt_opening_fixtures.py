#!/usr/bin/env python3
"""Extract dated foreign opening-fixture facts from the local DuckDB snapshot.

This is a source-receipt generator, not a PM99 writer.  It deliberately keeps
the Transfermarkt-derived facts separate from fixed PM99 carriers: matching a
2015 club name to a carrier, assigning roster slots, changing an opening grid
or writing a club record are separate, stricter decisions.

For each supported foreign domestic-league club, the receipt records:

* its earliest 2015/16 domestic fixture in the snapshot;
* the source XI, named substitutes, declared manager and declared formation;
* the reported stadium for that fixture; and
* the earliest *home* domestic fixture's reported stadium as a ground
  evidence item.

The last item is intentionally not called a permanent club ground: a match
report can use a neutral venue.  The source also has no stadium capacity, kit,
portrait or player-rating information, so this extractor cannot complete a
club release transaction on its own.

``duckdb`` is an optional runtime dependency because the source is a DuckDB
file.  Unit tests exercise the receipt construction with fixture-shaped rows
and do not require the package or the local source snapshot.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = "pm99-world-2015-transfermarkt-opening-fixtures-v1"
# ``SCHEMA`` above is the immutable, published 2015/16 receipt contract.
# New seasons use this distinct schema through the generic command wrapper.
# Keeping the two names separate prevents an old 2015 receipt from being
# represented as though it had been generated by a later, wider selection
# contract.
GENERIC_SCHEMA = "pm99-transfermarkt-opening-fixtures-v2"
DATASET_PROJECT_URL = "https://github.com/jso-w/transfermarkt-datasets-f"

# This intentionally excludes England.  English first-fixture evidence has a
# dedicated, carrier-mapped source lane; this receipt qualifies the currently
# captured foreign leagues only.  Adding a country is a source-contract change,
# not an automatic consequence of a newer third-party database snapshot.
SUPPORTED_FOREIGN_COUNTRIES: dict[str, str] = {
    "Belgium": "belgium",
    "Denmark": "denmark",
    "France": "france",
    "Germany": "ger",
    "Greece": "greece",
    "Italy": "italy",
    "Netherlands": "netherl",
    "Portugal": "portugal",
    "Russia": "russia",
    "Scotland": "scots",
    "Spain": "spain",
    "Türkiye": "turkey",
    "Ukraine": "ukraine",
}

REQUIRED_COLUMNS: dict[str, set[str]] = {
    "competitions": {"competition_id", "name", "country_name", "url"},
    "games": {
        "game_id", "competition_id", "season", "date", "home_club_id",
        "away_club_id", "home_club_name", "away_club_name",
        "home_club_manager_name", "away_club_manager_name", "stadium", "url",
        "home_club_formation", "away_club_formation", "competition_type",
    },
    "game_lineups": {
        "game_id", "club_id", "player_id", "player_name", "type", "position",
        "number", "team_captain",
    },
}


class SourceReceiptError(ValueError):
    """The local snapshot does not satisfy the source contract."""


def validate_country_mapping(country_mapping: Mapping[str, str]) -> dict[str, str]:
    """Return a checked source-country -> PM99 catalogue mapping.

    A country selection is part of the historical source contract.  It must
    therefore be explicit and complete for a run; this function deliberately
    rejects empty names, duplicate catalogue destinations and accidental
    aliases rather than choosing a country from a database query result.
    """

    if not country_mapping:
        raise SourceReceiptError("country mapping must select at least one source country")
    cleaned: dict[str, str] = {}
    destinations: set[str] = set()
    for raw_country, raw_catalogue in country_mapping.items():
        country = _text(raw_country)
        catalogue = _text(raw_catalogue)
        if country is None or catalogue is None:
            raise SourceReceiptError("country mapping has a blank source country or PM99 catalogue")
        if country in cleaned:
            raise SourceReceiptError(f"country mapping has a duplicate source country {country!r}")
        if catalogue in destinations:
            raise SourceReceiptError(f"country mapping has a duplicate PM99 catalogue {catalogue!r}")
        cleaned[country] = catalogue
        destinations.add(catalogue)
    return dict(sorted(cleaned.items()))


def canonical_json_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _text(value: object) -> str | None:
    text = str(value or "").strip()
    return text or None


def _date_text(value: object) -> str:
    if isinstance(value, date):
        return value.isoformat()
    text = _text(value)
    if text is None:
        raise SourceReceiptError("fixture source row has no date")
    return text


def _number_key(value: object) -> tuple[int, int | str]:
    text = _text(value)
    if text is not None and text.isdigit():
        return (0, int(text))
    return (1, text or "")


def _lineup_player(row: Mapping[str, Any]) -> dict[str, Any]:
    player_id = row.get("player_id")
    if player_id is None:
        raise SourceReceiptError("lineup row has no player id")
    name = _text(row.get("player_name"))
    if name is None:
        raise SourceReceiptError(f"lineup player {player_id} has no name")
    return {
        "player_id": int(player_id),
        "name": name,
        "position": _text(row.get("position")),
        "shirt_number": _text(row.get("number")),
        "team_captain": bool(int(row.get("team_captain") or 0)),
    }


def _fixture_base(row: Mapping[str, Any]) -> dict[str, Any]:
    club_id = row.get("club_id")
    game_id = row.get("game_id")
    if club_id is None or game_id is None:
        raise SourceReceiptError("fixture source row has no club or game id")
    club_name = _text(row.get("club_name"))
    country_name = _text(row.get("country_name"))
    competition_id = _text(row.get("competition_id"))
    competition_name = _text(row.get("competition_name"))
    venue = _text(row.get("venue"))
    if not all((club_name, country_name, competition_id, competition_name)) or venue not in {"home", "away"}:
        raise SourceReceiptError("fixture source row has incomplete club, competition or venue facts")
    return {
        "source_club_id": int(club_id),
        "source_club_name": club_name,
        "country_name": country_name,
        "competition": {
            "source_competition_id": competition_id,
            "name": competition_name,
            "source_url": _text(row.get("competition_url")),
        },
        "fixture": {
            "source_game_id": str(game_id),
            "date": _date_text(row.get("fixture_date")),
            "source_url": _text(row.get("game_url")),
            "venue": venue,
            "home_club": {"source_club_id": int(row["home_club_id"]), "name": _text(row.get("home_club_name"))},
            "away_club": {"source_club_id": int(row["away_club_id"]), "name": _text(row.get("away_club_name"))},
            "declared_manager": _text(row.get("club_manager_name")),
            "declared_formation": _text(row.get("club_formation")),
            "reported_match_stadium": _text(row.get("stadium")),
        },
    }


def _opening_record(rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    if not rows:
        raise SourceReceiptError("cannot build an opening fixture from no rows")
    base = _fixture_base(rows[0])
    fixture_id = base["fixture"]["source_game_id"]
    club_id = base["source_club_id"]
    for row in rows[1:]:
        candidate = _fixture_base(row)
        if candidate["fixture"]["source_game_id"] != fixture_id or candidate["source_club_id"] != club_id:
            raise SourceReceiptError("opening fixture rows are not a single club/game pair")

    starting: list[dict[str, Any]] = []
    substitutes: list[dict[str, Any]] = []
    unknown_types: set[str] = set()
    for row in rows:
        lineup_type = _text(row.get("lineup_type"))
        if row.get("player_id") is None:
            continue
        player = _lineup_player(row)
        if lineup_type == "starting_lineup":
            starting.append(player)
        elif lineup_type == "substitutes":
            substitutes.append(player)
        else:
            unknown_types.add(lineup_type or "<missing>")
    starting.sort(key=lambda row: (_number_key(row["shirt_number"]), row["player_id"]))
    substitutes.sort(key=lambda row: (_number_key(row["shirt_number"]), row["player_id"]))
    blockers: list[str] = []
    if len(starting) != 11:
        blockers.append(f"expected-11-starting-lineup-got-{len(starting)}")
    if base["fixture"]["declared_manager"] is None:
        blockers.append("missing-declared-manager")
    if base["fixture"]["declared_formation"] is None:
        blockers.append("missing-declared-formation")
    if base["fixture"]["reported_match_stadium"] is None:
        blockers.append("missing-reported-match-stadium")
    for lineup_type in sorted(unknown_types):
        blockers.append(f"unsupported-lineup-type-{lineup_type}")
    base["fixture"].update({
        "starting_lineup": starting,
        "substitutes": substitutes,
        "lineup_counts": {"starting_lineup": len(starting), "substitutes": len(substitutes)},
        "source_status": "source-qualified" if not blockers else "requires-review",
        "source_blockers": blockers,
    })
    return base


def _home_ground_record(row: Mapping[str, Any]) -> dict[str, Any]:
    base = _fixture_base(row)
    if base["fixture"]["venue"] != "home":
        raise SourceReceiptError("home-ground evidence must be a home fixture")
    stadium = base["fixture"]["reported_match_stadium"]
    return {
        "source_game_id": base["fixture"]["source_game_id"],
        "date": base["fixture"]["date"],
        "source_url": base["fixture"]["source_url"],
        "reported_stadium": stadium,
        "source_status": "source-qualified" if stadium is not None else "requires-review",
        "source_blockers": [] if stadium is not None else ["missing-reported-home-match-stadium"],
        "interpretation": "reported stadium for the first home domestic fixture; not proof of a persistent club ground or capacity",
    }


def build_receipt(
    *,
    opening_rows: Iterable[Mapping[str, Any]],
    first_home_rows: Iterable[Mapping[str, Any]],
    source: Mapping[str, Any],
    season: str = "2015",
    country_mapping: Mapping[str, str] | None = None,
    schema_version: str = SCHEMA,
) -> dict[str, Any]:
    """Build a canonical source-only receipt from deterministic query rows."""

    selected_countries = validate_country_mapping(country_mapping or SUPPORTED_FOREIGN_COUNTRIES)

    grouped_opening: dict[int, list[Mapping[str, Any]]] = defaultdict(list)
    for row in opening_rows:
        if row.get("club_id") is None:
            raise SourceReceiptError("opening query has no club id")
        grouped_opening[int(row["club_id"])].append(row)
    first_home_by_club: dict[int, Mapping[str, Any]] = {}
    for row in first_home_rows:
        if row.get("club_id") is None:
            raise SourceReceiptError("home fixture query has no club id")
        club_id = int(row["club_id"])
        if club_id in first_home_by_club:
            raise SourceReceiptError(f"home fixture query has multiple first rows for club {club_id}")
        first_home_by_club[club_id] = row

    clubs: list[dict[str, Any]] = []
    for club_id in sorted(grouped_opening):
        opening = _opening_record(grouped_opening[club_id])
        if opening["country_name"] not in selected_countries:
            raise SourceReceiptError(f"unsupported country escaped source query: {opening['country_name']}")
        home_row = first_home_by_club.get(club_id)
        if home_row is None:
            ground_evidence = {
                "source_status": "requires-review",
                "source_blockers": ["no-domestic-home-fixture-in-source"],
                "interpretation": "no ground evidence available from the source snapshot",
            }
        else:
            ground_evidence = _home_ground_record(home_row)
        clubs.append({
            "country_catalog": selected_countries[opening["country_name"]],
            "country_name": opening.pop("country_name"),
            "source_club": {
                "id": opening.pop("source_club_id"),
                "name": opening.pop("source_club_name"),
            },
            "competition": opening.pop("competition"),
            "opening_fixture": opening.pop("fixture"),
            "first_home_fixture_ground_evidence": ground_evidence,
            "compiler_disposition": "source-fact-only; no-pm99-carrier-or-slot-assignment",
        })
    if set(first_home_by_club) - set(grouped_opening):
        raise SourceReceiptError("home fixture query includes a club absent from opening-fixture query")
    found_countries = {str(row["country_name"]) for row in clubs}
    expected_countries = set(selected_countries)
    if found_countries != expected_countries:
        missing = sorted(expected_countries - found_countries)
        unexpected = sorted(found_countries - expected_countries)
        raise SourceReceiptError(f"source country coverage changed (missing={missing}, unexpected={unexpected})")

    per_country: dict[str, Counter[str]] = defaultdict(Counter)
    for club in clubs:
        country = str(club["country_name"])
        fixture = club["opening_fixture"]
        per_country[country]["clubs"] += 1
        per_country[country]["opening_xi_source_qualified"] += int(fixture["lineup_counts"]["starting_lineup"] == 11)
        per_country[country]["manager_present"] += int(fixture["declared_manager"] is not None)
        per_country[country]["formation_present"] += int(fixture["declared_formation"] is not None)
        per_country[country]["opening_match_stadium_present"] += int(fixture["reported_match_stadium"] is not None)
        per_country[country]["home_fixture_stadium_present"] += int(
            club["first_home_fixture_ground_evidence"].get("reported_stadium") is not None
        )
    summary = {
        "foreign_country_count": len(found_countries),
        "club_count": len(clubs),
        "opening_xi_source_qualified_club_count": sum(
            int(club["opening_fixture"]["lineup_counts"]["starting_lineup"] == 11) for club in clubs
        ),
        "manager_present_club_count": sum(int(club["opening_fixture"]["declared_manager"] is not None) for club in clubs),
        "formation_present_club_count": sum(int(club["opening_fixture"]["declared_formation"] is not None) for club in clubs),
        "opening_match_stadium_present_club_count": sum(
            int(club["opening_fixture"]["reported_match_stadium"] is not None) for club in clubs
        ),
        "home_fixture_stadium_present_club_count": sum(
            int(club["first_home_fixture_ground_evidence"].get("reported_stadium") is not None) for club in clubs
        ),
        "countries": {country: dict(sorted(counts.items())) for country, counts in sorted(per_country.items())},
    }
    return {
        "schema_version": schema_version,
        "season": str(season),
        "source": dict(source),
        "selection_policy": {
            "opening_fixture": "earliest domestic-league fixture per source club, ordered by date then source game id",
            "ground_evidence": "earliest domestic home fixture per source club, ordered by date then source game id",
            "country_scope": "explicit source-country to PM99-catalogue mapping supplied for this receipt",
            "no_inference": [
                "reported match stadium is not promoted to a persistent club ground or capacity",
                "no player ratings, kits, portraits or PM99 carrier assignments are supplied",
                "no source row changes PM99 country, competition, division, roster size, tactics grid or player slot",
            ],
        },
        "summary": summary,
        "clubs": clubs,
    }


def _import_duckdb() -> Any:
    try:
        import duckdb  # type: ignore[import-not-found]
    except ModuleNotFoundError as exc:
        raise SourceReceiptError(
            "DuckDB Python package is required to read the source snapshot; install `duckdb` in the execution environment"
        ) from exc
    return duckdb


def _column_names(connection: Any, table: str) -> set[str]:
    return {str(row[0]) for row in connection.execute(f"DESCRIBE {table}").fetchall()}


def _validate_snapshot_schema(connection: Any) -> None:
    tables = {str(row[0]) for row in connection.execute("SHOW TABLES").fetchall()}
    for table, required in REQUIRED_COLUMNS.items():
        if table not in tables:
            raise SourceReceiptError(f"DuckDB source has no required table {table}")
        missing = sorted(required - _column_names(connection, table))
        if missing:
            raise SourceReceiptError(f"DuckDB {table} misses required column(s): {', '.join(missing)}")


OPENING_QUERY = """
WITH perspectives AS (
    SELECT
        g.game_id, g.date AS fixture_date, g.competition_id, c.name AS competition_name,
        c.country_name, c.url AS competition_url, g.url AS game_url, g.stadium,
        g.home_club_id, g.home_club_name, g.away_club_id, g.away_club_name,
        g.home_club_id AS club_id, g.home_club_name AS club_name, 'home' AS venue,
        g.home_club_manager_name AS club_manager_name, g.home_club_formation AS club_formation
    FROM games AS g
    INNER JOIN competitions AS c USING (competition_id)
    WHERE g.season = ? AND g.competition_type = 'domestic_league' AND c.country_name IN ({country_placeholders})
    UNION ALL
    SELECT
        g.game_id, g.date AS fixture_date, g.competition_id, c.name AS competition_name,
        c.country_name, c.url AS competition_url, g.url AS game_url, g.stadium,
        g.home_club_id, g.home_club_name, g.away_club_id, g.away_club_name,
        g.away_club_id AS club_id, g.away_club_name AS club_name, 'away' AS venue,
        g.away_club_manager_name AS club_manager_name, g.away_club_formation AS club_formation
    FROM games AS g
    INNER JOIN competitions AS c USING (competition_id)
    WHERE g.season = ? AND g.competition_type = 'domestic_league' AND c.country_name IN ({country_placeholders})
), ranked AS (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY club_id ORDER BY fixture_date, game_id) AS fixture_rank
    FROM perspectives
), first_fixtures AS (
    SELECT * FROM ranked WHERE fixture_rank = 1
)
SELECT
    f.*, l.player_id, l.player_name, l.type AS lineup_type, l.position, l.number, l.team_captain
FROM first_fixtures AS f
LEFT JOIN game_lineups AS l ON l.game_id::VARCHAR = f.game_id AND l.club_id = f.club_id
ORDER BY f.country_name, f.competition_id, f.club_name, f.club_id, l.type, l.number, l.player_id
"""

FIRST_HOME_QUERY = """
WITH perspectives AS (
    SELECT
        g.game_id, g.date AS fixture_date, g.competition_id, c.name AS competition_name,
        c.country_name, c.url AS competition_url, g.url AS game_url, g.stadium,
        g.home_club_id, g.home_club_name, g.away_club_id, g.away_club_name,
        g.home_club_id AS club_id, g.home_club_name AS club_name, 'home' AS venue,
        g.home_club_manager_name AS club_manager_name, g.home_club_formation AS club_formation
    FROM games AS g
    INNER JOIN competitions AS c USING (competition_id)
    WHERE g.season = ? AND g.competition_type = 'domestic_league' AND c.country_name IN ({country_placeholders})
), ranked AS (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY club_id ORDER BY fixture_date, game_id) AS fixture_rank
    FROM perspectives
)
SELECT * FROM ranked WHERE fixture_rank = 1
ORDER BY country_name, competition_id, club_name, club_id
"""


def _fetch_dict_rows(connection: Any, query: str, parameters: Sequence[object]) -> list[dict[str, Any]]:
    cursor = connection.execute(query, list(parameters))
    names = [str(column[0]) for column in cursor.description]
    return [dict(zip(names, row, strict=True)) for row in cursor.fetchall()]


def extract_receipt(
    *,
    database: Path,
    season: str = "2015",
    country_mapping: Mapping[str, str] | None = None,
    schema_version: str = SCHEMA,
) -> dict[str, Any]:
    if not database.is_file():
        raise SourceReceiptError(f"DuckDB source does not exist: {database}")
    selected_countries = validate_country_mapping(country_mapping or SUPPORTED_FOREIGN_COUNTRIES)
    duckdb = _import_duckdb()
    connection = duckdb.connect(str(database), read_only=True)
    try:
        _validate_snapshot_schema(connection)
        countries = sorted(selected_countries)
        placeholders = ", ".join("?" for _ in countries)
        opening_query = OPENING_QUERY.format(country_placeholders=placeholders)
        home_query = FIRST_HOME_QUERY.format(country_placeholders=placeholders)
        opening_rows = _fetch_dict_rows(connection, opening_query, [season, *countries, season, *countries])
        home_rows = _fetch_dict_rows(connection, home_query, [season, *countries])
        version_rows = connection.execute("SELECT * FROM version").fetchall()
        version = str(version_rows[0][0]) if len(version_rows) == 1 and version_rows[0] else None
    finally:
        connection.close()
    if not opening_rows:
        raise SourceReceiptError(f"no supported foreign {season}/16 opening-fixture rows in DuckDB source")
    return build_receipt(
        opening_rows=opening_rows,
        first_home_rows=home_rows,
        season=season,
        country_mapping=selected_countries,
        schema_version=schema_version,
        source={
            "dataset_project_url": DATASET_PROJECT_URL,
            "database_path": str(database),
            "database_sha256": sha256_file(database),
            "database_version": version,
            "selection_query_version": "opening-fixtures-v2" if schema_version == GENERIC_SCHEMA else "foreign-opening-fixtures-v1",
            "country_mapping": selected_countries,
        },
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", required=True, type=Path, help="local Transfermarkt-derived DuckDB snapshot")
    parser.add_argument("--season", default="2015", help="source season label (default: 2015 for 2015/16)")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        receipt = extract_receipt(database=args.database, season=args.season)
    except (OSError, SourceReceiptError) as exc:
        parser.error(str(exc))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(canonical_json_bytes(receipt))
    print(json.dumps(receipt["summary"], sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
