#!/usr/bin/env python3
"""Allocate compatible mode-0 carriers for actual 2015 shared-JUG demands.

The output is a reviewed compiler input, not a binary writer.  Every selected
mode-0 carrier is exclusive, dd6361, role-compatible and used once.  Its
appended replacement ID is chosen above the current JUG directory maximum.
"""

from __future__ import annotations

try:
    from scripts import json_storage_io_v1 as storage_io
except ModuleNotFoundError:
    import sys as _storage_sys
    from pathlib import Path as _StoragePath
    _storage_sys.path.insert(0, str(next(p for p in _StoragePath(__file__).resolve().parents if (p / 'scripts/json_storage_io_v1.py').is_file())))
    from scripts import json_storage_io_v1 as storage_io

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any


SCHEMA = "pm99-world-2015-mode1-recycle-allocation-v1"
ROOT = storage_io.resolve(Path(__file__)).parents[1]
EDITOR = ROOT / "upstream" / "pm99-skezmod-db-editor"
for candidate in (ROOT, EDITOR):
    if str(candidate) not in sys.path:
        sys.path.insert(0, str(candidate))


def _sha(path: Path) -> str:
    return hashlib.sha256(storage_io.read_bytes(path)).hexdigest()


def allocate(*, capacity_path: Path, demand_path: Path, jug_path: Path) -> dict[str, Any]:
    capacity = json.loads(storage_io.read_text(capacity_path, encoding='utf-8'))
    demand = json.loads(storage_io.read_text(demand_path, encoding='utf-8'))
    if demand["runtime_unqualified_required_role_codes"]:
        raise ValueError("demand contains a runtime-unqualified fine-role code")

    # Import lazily so fixture-only tests can exercise allocation policy with a
    # minimal indexed file generated by the editor test helpers.
    from app.fdi_indexed import IndexedFDIFile

    jug_data = storage_io.read_bytes(jug_path)
    existing_ids = {int(entry.record_id) for entry in IndexedFDIFile.from_bytes(jug_data).entries}
    next_id = max(existing_ids) + 1
    candidates = {
        int(role): list(rows)
        for role, rows in capacity["eligible_mode0_dd6361_sources_by_primary_role"].items()
    }
    used_sources: set[int] = set()
    allocations: list[dict[str, Any]] = []
    for row in sorted(
        demand["demands"],
        key=lambda item: (int(item["recycle_team_carrier_id"]), int(item["slot_index"])),
    ):
        role = int(row["required_primary_fine_role_code"])
        source = next(
            (candidate for candidate in candidates.get(role, []) if int(candidate["carrier_id"]) not in used_sources),
            None,
        )
        if source is None:
            raise ValueError(f"no unused compatible mode-0 source remains for role {role}")
        while next_id in existing_ids:
            next_id += 1
        source_id = int(source["carrier_id"])
        allocations.append({
            "recycle_team_carrier_id": int(row["recycle_team_carrier_id"]),
            "recycle_team_slot_index": int(row["slot_index"]),
            "historical_player_name": str(row["historical_player_name"]),
            "old_shared_mode1_carrier_id": int(row["player_carrier_id"]),
            "new_foreign_player_carrier_id": source_id,
            "mode1_compact_donor_carrier_id": int(row["player_carrier_id"]),
            "mode0_source_team_carrier_id": int(source["mode0_team_carrier_id"]),
            "mode0_source_player_carrier_id": source_id,
            "appended_mode0_clone_carrier_id": next_id,
            "required_primary_fine_role_code": role,
            "source_role_candidates": list(source["role_candidates"]),
            "source_baseline_name": source.get("baseline_name"),
        })
        used_sources.add(source_id)
        existing_ids.add(next_id)
        next_id += 1

    return {
        "schema_version": SCHEMA,
        "sources": {
            "capacity_audit_sha256": _sha(capacity_path),
            "role_demand_sha256": _sha(demand_path),
            "jug98030_sha256": _sha(jug_path),
        },
        "policy": "one exclusive compatible dd6361 source and one fresh appended clone per required foreign duplicate slot",
        "allocation_count": len(allocations),
        "unique_mode0_source_count": len(used_sources),
        "unallocated_duplicate_slot_count": int(demand["unresolved_duplicate_slot_count"]),
        "allocations": allocations,
        "result": "allocated-selected-carriers" if len(allocations) == int(demand["recycle_demand_count"]) else "blocked",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capacity-audit", required=True, type=Path)
    parser.add_argument("--role-demand", required=True, type=Path)
    parser.add_argument("--jug", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    result = allocate(
        capacity_path=storage_io.resolve(args.capacity_audit),
        demand_path=storage_io.resolve(args.role_demand),
        jug_path=storage_io.resolve(args.jug),
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    storage_io.write_text(args.output, json.dumps(result, ensure_ascii=False, sort_keys=True, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({"output": str(args.output), "allocation_count": result["allocation_count"]}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
